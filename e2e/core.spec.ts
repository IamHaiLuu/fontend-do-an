  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await page.getByRole('button', { name: 'Xác nhận và thanh toán' }).click()
  await page.getByRole('button', { name: 'Mô phỏng thành công' }).click()
  await expect(page.getByRole('heading', { name: 'Đặt phòng đã được xác nhận' })).toBeVisible()
  await page.getByRole('link', { name: 'Chi tiết booking' }).click()
  await page.getByRole('button', { name: 'Hủy booking' }).click()
  await page.getByRole('button', { name: 'Xác nhận hủy' }).click()
  await expect(page.getByText('Đã hủy booking. Yêu cầu hoàn tiền đang chờ xử lý.')).toBeVisible()
  await expect(page.getByText('Đã hủy', { exact: true }).first()).toBeVisible()
  const bookingUrl = page.url()
  await page.goto('/auth/login')
  await page.getByRole('button', { name: /Quản trị: admin@demo.vn/ }).click()
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await page.goto('/admin')
  await page.getByRole('button', { name: 'Bắt đầu xử lý demo' }).click()
  await page.getByRole('button', { name: 'Hoàn thành demo' }).click()
  await page.goto('/auth/login')
  await page.getByRole('button', { name: /Du khách: khach@demo.vn/ }).click()
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await page.goto(bookingUrl)
